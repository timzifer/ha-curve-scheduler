const LANGUAGES: Record<string, Record<TranslationKey, string>> = { en, de };

export type Translate = (key: TranslationKey, params?: Record<string, unknown>) => string;

export function languageOf(hass?: {
  locale?: { language?: string };
  language?: string;
}): string {
  const language = hass?.locale?.language ?? hass?.language ?? "en";
  return language.toLowerCase().startsWith("de") ? "de" : "en";
}

export function translator(language: string): Translate {
  const table = LANGUAGES[language] ?? en;
  return (key, params = {}) => {
    const template = table[key] ?? en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name: string) =>
      name in params ? String(params[name]) : `{${name}}`,
    );
  };
}

export function isTranslationKey(key: string): key is TranslationKey {
  return key in en;
}
